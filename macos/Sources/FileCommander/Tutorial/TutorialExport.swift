import AppKit
import ExplainerKit
import FCKit
import SwiftUI

/// `--export-explainer <id|all> --out DIR [--appearance light|dark|both] [--speed N]`
/// plays explainers in a fixed-size window and writes, for each, a movie,
/// SRT and VTT captions, a still per caption, a preview GIF and a README.md.
extension TutorialCoordinator {
  func export(_ which: String, arguments: [String]) {
    func option(_ name: String) -> String? {
      arguments.firstIndex(of: name).flatMap { $0 + 1 < arguments.count ? arguments[$0 + 1] : nil }
    }
    let out = URL(fileURLWithPath: option("--out") ?? "explainers-out", isDirectory: true)
    let appearances: [AppPreferences.Appearance] = switch option("--appearance") ?? "light" {
    case "dark": [.dark]
    case "both": [.light, .dark]
    default: [.light]
    }
    let speed = Double(option("--speed") ?? "") ?? 1.5
    // Explainers that restart the app can't record themselves.
    let scripts = (which == "all" ? catalog.scripts : catalog.scripts.filter { $0.id == which })
      .filter { !$0.needs("crash") && !$0.needs("restart") }
    quitWhenDone = true
    Task { @MainActor in
      var failures: [String] = []
      for script in scripts {
        do {
          try await exportOne(script, to: out.appendingPathComponent(script.id), appearances: appearances, speed: speed)
        } catch {
          failures.append("\(script.id): \(error.localizedDescription)")
        }
      }
      var index = "# File Commander explainers\n\nGenerated by `File Commander --export-explainer`.\n\n"
      for chapter in catalog.chapters {
        index += "## \(chapter.title)\n\n"
        for script in catalog.scripts(in: chapter.id) where scripts.contains(where: { $0.id == script.id }) {
          index += "- [\(script.title)](\(script.id)/README.md) — \(script.summary)\n"
        }
        index += "\n"
      }
      try? index.write(to: out.appendingPathComponent("index.md"), atomically: true, encoding: .utf8)
      for failure in failures { FileHandle.standardError.write(Data("export failed: \(failure)\n".utf8)) }
      exit(failures.isEmpty ? 0 : 1)
    }
  }

  private func exportOne(_ script: ExplainerScript, to folder: URL, appearances: [AppPreferences.Appearance], speed: Double) async throws {
    let steps = folder.appendingPathComponent("steps")
    try FileManager.default.createDirectory(at: steps, withIntermediateDirectories: true)
    guard let window = mainWindow ?? NSApp.windows.first(where: { $0.identifier?.rawValue.hasPrefix("main") == true }) else { return }
    mainWindow = window
    var stills: [String: [String]] = [:]
    var cues: [ExplainerExport.Cue] = []
    for (pass, appearance) in appearances.enumerated() {
      app.preferences.appearance = appearance
      if let screen = window.screen ?? NSScreen.main {
        let size = CGSize(width: 1280, height: 800)
        window.setFrame(CGRect(x: screen.visibleFrame.midX - size.width / 2, y: screen.visibleFrame.midY - size.height / 2,
                               width: size.width, height: size.height), display: true)
      }
      window.makeKeyAndOrderFront(nil)
      try await Task.sleep(for: .milliseconds(600))
      let region = window.frame
      let recorder = ExplainerRecorder()
      if pass == 0 { try await recorder.start(region: region, output: folder.appendingPathComponent("\(script.id).mp4")) }
      runner.speed = speed
      runner.mode = .watch
      annotations.show(over: window, runner: runner, style: overlayStyle, controlsView: AnyView(EmptyView()))
      var captions = 0
      let suffix = appearance == .dark ? "dark" : "light"
      runner.onStep = { [weak self] _, _ in
        guard let self else { return }
        let count = self.runner.timeline.filter { $0.kind == "caption" }.count
        guard count > captions else { return }
        captions = count
        let key = String(format: "%02d", count)
        let file = "steps/\(key)-\(suffix).png"
        stills[key, default: []].append(file)
        Task { @MainActor in
          try? await Task.sleep(for: .milliseconds(700))
          try? await ExplainerRecorder.still(region: region, to: folder.appendingPathComponent(file))
        }
      }
      defer { runner.onStep = nil }
      let started = Date()
      do {
        try await runner.run(script, host: self)
      } catch {
        await recorder.stop()
        annotations.hide()
        await finish(script, keepTabs: false)
        throw error
      }
      try await Task.sleep(for: .milliseconds(900))
      await recorder.stop()
      annotations.hide()
      await finish(script, keepTabs: true)
      if pass == 0 { cues = ExplainerExport.cues(runner.timeline, end: Date().timeIntervalSince(started)) }
    }
    app.engine.closeTutorialTabs()
    world.remove()
    try ExplainerExport.srt(cues).write(to: folder.appendingPathComponent("\(script.id).srt"), atomically: true, encoding: .utf8)
    try ExplainerExport.vtt(cues).write(to: folder.appendingPathComponent("\(script.id).vtt"), atomically: true, encoding: .utf8)
    let firstLook = appearances.first == .dark ? "dark" : "light"
    let frames = stills.keys.sorted().compactMap { key in stills[key]?.first { $0.contains(firstLook) } }.map { folder.appendingPathComponent($0) }
    ExplainerRecorder.gif(from: frames, to: folder.appendingPathComponent("preview.gif"))
    let page = ExplainerExport.markdown(script: script, cues: cues, stills: stills, video: "\(script.id).mp4", preview: "preview.gif")
    try page.write(to: folder.appendingPathComponent("README.md"), atomically: true, encoding: .utf8)
  }
}
