#!/usr/bin/env python3
"""Build the deterministic demo world that the promo storyboard plays in.

The world is a throwaway directory tree: `home/` holds the files the panels
show, `profile/` is HOME for FC and Fresh (their own settings and data), and
`config/` is FC's profile. Recording never touches the real user's files.

The SSH scene uses a real host from your ~/.ssh/config (default `dev`). Its
demo website is written to a remote directory (default /tmp/fc), which is only
ever replaced when a sibling `<dir>.promo-world` marker shows that this script
created it.
"""
import argparse
import datetime
import json
import os
from pathlib import Path
import io
import shlex
import shutil
import subprocess
import sys
import tarfile

MARKER = '.fc-promo-world'
REPO = Path(__file__).resolve().parents[2]
MIB = 1024 * 1024


def stamp(path, day, hour=10, minute=0):
    when = datetime.datetime(2026, 9, day, hour, minute).timestamp()
    os.utime(path, (when, when), follow_symlinks=False)


def text_file(path, body, day):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(body)
    stamp(path, day)


def sized_file(path, size, day):
    """Sparse files keep the world quick to build; copies still move every byte."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open('wb') as stream:
        stream.truncate(size)
    stamp(path, day)


def find_7zr(explicit):
    candidates = [explicit] if explicit else [REPO / 'build-release/third_party/lzma/_o/7zr', shutil.which('7zr'), shutil.which('7z')]
    for candidate in candidates:
        if candidate and Path(candidate).is_file() and os.access(candidate, os.X_OK):
            return str(candidate)
    raise SystemExit('7zr not found: build FC first or pass --7zr')


def build(root, rate, sevenzip, ssh_host, remote_dir):
    home, config, server = root / 'home', root / 'config' / 'file_commander', root / 'server'
    profile = root / 'profile'

    for number in range(2041, 2065):
        sized_file(home / 'camera' / f'IMG_{number}.jpg', (2 + number % 5) * MIB + number * 997, 20 + number % 7)
    for number in range(31, 37):
        sized_file(home / 'camera' / f'MOV_00{number}.mov', (18 + number % 4) * MIB, 26)
    for name, day in (('beach.jpg', 3), ('city.jpg', 4), ('harbour.jpg', 6)):
        sized_file(home / 'photos' / '2026' / name, 3 * MIB + day * 4099, day)
    for name, day in (('mountains.jpg', 12), ('lake.jpg', 14)):
        sized_file(home / 'photos' / '2025' / name, 2 * MIB + day * 811, day)

    albums = {'Night Drive': ['Neon Rain', 'Coastline', 'After Hours', 'Slow Lights'],
              'Field Notes': ['North Wind', 'Paper Maps', 'Low Tide']}
    for album, tracks in albums.items():
        for index, track in enumerate(tracks, 1):
            sized_file(home / 'music' / album / f'{index:02} {track}.flac', (34 + index * 3) * MIB, 11 + index)
    (home / 'backup').mkdir(parents=True, exist_ok=True)

    site = {'index.html': '<!doctype html>\n<title>Field Notes</title>\n<h1>Field Notes</h1>\n<p>Photos and music from the road.</p>\n',
            'style.css': 'body { font: 18px/1.5 system-ui; margin: 4rem auto; max-width: 42rem; }\nh1 { color: #2d6cdf; }\n',
            'app.js': "document.querySelector('h1').addEventListener('click', () => alert('Hello!'));\n",
            'README.md': '# Field Notes website\n\nStatic site. Upload `index.html`, `style.css` and `app.js` to the server.\n'}
    for name, body in site.items():
        text_file(home / 'projects' / 'website' / name, body, 22)
    text_file(home / 'projects' / 'notes' / 'ideas.md', '# Ideas\n\n- Print the harbour photos\n- Finish the coastline track\n', 18)
    text_file(home / 'projects' / 'notes' / 'todo.md', '# To do\n\n- [ ] Back up the music folder\n- [ ] Publish the website\n', 19)
    text_file(home / 'todo.txt', 'Back up music\nPublish website\nSort camera roll\n', 25)
    text_file(home / 'README.md', '# Demo home\n\nEverything here was generated by tools/promo/make_world.py.\n', 1)

    archive = home / 'website-2025.7z'
    subprocess.run([sevenzip, 'a', '-bd', '-y', str(archive), '.'], cwd=home / 'projects' / 'website',
                   check=True, stdout=subprocess.DEVNULL)
    stamp(archive, 2)

    # Staged locally, then unpacked into the remote directory by populate_remote().
    for name, body in (('index.html', '<!doctype html>\n<title>Field Notes</title>\n<h1>Coming soon</h1>\n'),
                       ('404.html', '<!doctype html>\n<title>Not found</title>\n<h1>Nothing here</h1>\n'),
                       ('robots.txt', 'User-agent: *\nAllow: /\n'),
                       ('assets/logo.svg', '<svg xmlns="http://www.w3.org/2000/svg" width="64" height="64"><circle cx="32" cy="32" r="28" fill="#2d6cdf"/></svg>\n')):
        text_file(server / name, body, 15)
    sized_file(server / 'assets' / 'hero.jpg', 384 * 1024, 15)

    config.mkdir(parents=True)
    settings = {'version': 1, 'transfer_rate_limit': rate,
                'bookmarks': [str(home / 'projects' / 'website'), str(home / 'photos' / '2026'), str(home / 'music')]}
    (config / 'settings.json').write_text(json.dumps(settings, indent=2) + '\n')

    # Fresh reads $HOME/.config/fresh on macOS. Keep the recording free of the
    # agent-session dock (it lists the real user's agent sessions), the
    # first-run Welcome tab and update notices.
    fresh_config = profile / '.config' / 'fresh'
    fresh_config.mkdir(parents=True)
    (fresh_config / 'config.json').write_text(json.dumps({
        'check_for_updates': False,
        'plugins': {'orchestrator': {'enabled': True, 'settings': {'autoOpenDock': 'never'}},
                    'welcome_screen': {'enabled': True, 'settings': {'showOnStartup': False}}}}, indent=2) + '\n')

    for directory in sorted((path for path in root.rglob('*') if path.is_dir()), key=lambda path: len(path.parts), reverse=True):
        stamp(directory, 28)
    (root / MARKER).write_text(json.dumps({'home': str(home), 'profile': str(profile), 'config': str(root / 'config'),
                                           'ssh_host': ssh_host, 'server': remote_dir}, indent=2) + '\n')


def ssh(host, command, data=None):
    return subprocess.run(['ssh', '-o', 'BatchMode=yes', '-o', 'ConnectTimeout=10', host, command],
                          input=data, stdout=subprocess.PIPE, stderr=subprocess.PIPE)


def check_ssh(host):
    result = ssh(host, 'python3 -c pass')
    if result.returncode == 0:
        print(f'SSH scene ready: {host} answers without a prompt and has python3.')
        return True
    print(f'SSH scene not ready (play.py --skip ssh leaves it out): {result.stderr.decode().strip() or result.returncode}')
    print(f'  `ssh {host} python3 -c pass` must succeed without asking for a password or host key.')
    return False


def populate_remote(root, host, remote_dir):
    """Replace the remote demo directory with the staged server files."""
    archive = io.BytesIO()
    with tarfile.open(fileobj=archive, mode='w', format=tarfile.GNU_FORMAT) as tar:
        for path in sorted((root / 'server').rglob('*')):
            tar.add(path, arcname=str(path.relative_to(root / 'server')), recursive=False)
    target = shlex.quote(remote_dir.rstrip('/'))
    script = (f'set -e; d={target}; m="$d.promo-world"; '
              f'if [ -e "$d" ] && [ ! -f "$m" ]; then echo "$d exists and was not created by the promo; refusing to replace it" >&2; exit 3; fi; '
              f'rm -rf "$d"; mkdir -p "$d"; touch "$m"; tar -xf - -C "$d"')
    result = ssh(host, script, archive.getvalue())
    if result.returncode != 0:
        raise SystemExit(f'could not populate {host}:{remote_dir}: {result.stderr.decode().strip()}')
    print(f'Remote demo directory ready: {host}:{remote_dir}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--root', type=Path, default=Path('/tmp/fc-promo'))
    parser.add_argument('--rate', type=int, default=12 * MIB, help='transfer_rate_limit in bytes per second (default 12 MiB/s)')
    parser.add_argument('--7zr', dest='sevenzip')
    parser.add_argument('--ssh-host', default='dev', help='SSH host alias for the SSH scene (default dev)')
    parser.add_argument('--remote-dir', default='/tmp/fc', help='absolute directory on the SSH host (default /tmp/fc)')
    parser.add_argument('--no-remote', action='store_true', help='build only the local world')
    parser.add_argument('--check-ssh', action='store_true', help='only check that the SSH host is usable')
    args = parser.parse_args()
    root = args.root.absolute()
    if not args.remote_dir.startswith('/') or args.remote_dir.rstrip('/') in ('', '/tmp', '/home', '/root'):
        raise SystemExit(f'--remote-dir must be a dedicated absolute directory, not {args.remote_dir!r}')
    if args.check_ssh:
        raise SystemExit(0 if check_ssh(args.ssh_host) else 1)
    if root.exists():
        if not (root / MARKER).is_file():
            raise SystemExit(f'{root} exists and is not a promo world; refusing to replace it')
        shutil.rmtree(root)
    root.mkdir(parents=True)
    build(root, args.rate, find_7zr(args.sevenzip), args.ssh_host, args.remote_dir)
    print(f'Promo world ready in {root}')
    if not args.no_remote and check_ssh(args.ssh_host):
        populate_remote(root, args.ssh_host, args.remote_dir)


if __name__ == '__main__':
    main()
