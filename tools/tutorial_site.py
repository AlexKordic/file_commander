#!/usr/bin/env python3
"""Fill the tutorial player in docs/tutorial from a recording and link it from README.md; never uploads, commits or pushes."""
import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import sys

REPO = Path(__file__).resolve().parent.parent
PLAYER_URL = 'https://alexkordic.github.io/file_commander/tutorial/'
BEGIN = '<!-- tutorial:begin (generated by tools/tutorial_site.py) -->'
END = '<!-- tutorial:end -->'
NS = 10**9


def tool(name):
    path = shutil.which(name)
    if not path:
        raise ValueError(f'{name} is not on PATH')
    return path


def run(*command):
    return subprocess.run(command, check=True, capture_output=True, text=True).stdout


def markdown(text):
    return ''.join('\\' + c if c in '\\[]|<>*_`' else c for c in text)


def readme_block(timeline, media, url, poster):
    chapters, lessons = timeline['chapters'], timeline['lessons']
    minutes = max(1, round(timeline['duration_ns'] / NS / 60))
    sound = ('It has no sound: captions explain every step, and the player can pause after each one.' if media['silent']
             else 'It is narrated and captioned, and the player can pause after each step.')
    jumps = ' · '.join(f'[{markdown(c["title"])}]({url}#chapter={c["id"]})' for c in chapters)
    rows = '\n'.join(
        f'| {markdown(c["title"])} | '
        + ' · '.join(f'[{markdown(l["title"])}]({url}#lesson={l["id"]})' for l in lessons if l['chapter'] == c['id']) + ' |'
        for c in chapters)
    return (f'{BEGIN}\n'
            f'<p align="center"><a href="{url}"><img src="{poster}" width="480" alt="Watch the {timeline["title"]}"></a></p>\n\n'
            f'**[Watch the tutorial]({url})**: {len(lessons)} short lessons in {minutes} minutes, recorded in the macOS app. {sound} '
            f'Chapters: {jumps}. Or [download the video]({url}{media["video"]}) ({media["bytes"] / 1e6:.1f} MB).\n\n'
            f'<details>\n<summary>All {len(lessons)} lessons</summary>\n\n| Chapter | Lessons |\n| --- | --- |\n{rows}\n\n</details>\n'
            f'{END}\n')


def place(readme, block):
    """Replace the marked block, or put it first: above the project heading."""
    text = readme.read_text()
    if BEGIN in text and END in text:
        before, rest = text.split(BEGIN, 1)
        after = rest.split(END, 1)[1].lstrip('\n')
        text = before + block + ('\n' + after if after else '')
    else:
        text = block + '\n' + text
    readme.write_text(text)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('recording', type=Path, help='recording folder that holds render/timeline.json')
    parser.add_argument('--movie', type=Path, help='movie to publish (default: render/tutorial-vfr-small.mp4 in the recording)')
    parser.add_argument('--site', type=Path, default=REPO / 'docs/tutorial', help='folder of the player page')
    parser.add_argument('--readme', type=Path, default=REPO / 'README.md')
    parser.add_argument('--url', default=PLAYER_URL, help='published address of the player page')
    args = parser.parse_args(argv)
    try:
        render = args.recording / 'render'
        movie = args.movie or render / 'tutorial-vfr-small.mp4'
        timeline = json.loads((render / 'timeline.json').read_text())
        probe = json.loads(run(tool('ffprobe'), '-v', 'error', '-select_streams', 'v:0', '-show_entries',
                               'stream=width,height:format=duration', '-of', 'json', str(movie)))
        width, height = probe['streams'][0]['width'], probe['streams'][0]['height']
        if abs(float(probe['format']['duration']) - timeline['duration_ns'] / NS) > 0.5:
            raise ValueError(f'{movie.name} is not as long as the timeline: it belongs to another recording')
        if abs(width / height - timeline['width'] / timeline['height']) > 0.01:
            raise ValueError(f'{movie.name} does not have the shape of the recorded window')
        url = args.url if args.url.endswith('/') else args.url + '/'
        site = args.site
        site.mkdir(parents=True, exist_ok=True)
        shutil.copyfile(movie, site / 'tutorial.mp4')
        shutil.copyfile(render / 'captions.vtt', site / 'captions.vtt')
        # The poster has the movie's size, so the page and the README show the same picture.
        run(tool('ffmpeg'), '-v', 'error', '-nostdin', '-y', '-i', str(render / 'poster.png'), '-vf',
            f'scale={width}:{height}:flags=lanczos', '-frames:v', '1', '-q:v', '3', str(site / 'poster.jpg'))
        frames = timeline.get('frames') or [{}]
        stamp = frames[0].get('utc', '')
        media = dict(video='tutorial.mp4', bytes=movie.stat().st_size, width=width, height=height,
                     # Without narration clips the sound track is silence, and the page plays it muted.
                     silent=not timeline.get('narration'),
                     recorded=f'{stamp[:4]}-{stamp[4:6]}-{stamp[6:8]}' if len(stamp) >= 8 else '')
        keys = ('schema', 'title', 'language', 'duration_ns', 'width', 'height', 'fps', 'chapters', 'lessons', 'steps')
        data = {key: timeline[key] for key in keys} | {'media': media}
        (site / 'timeline.js').write_text(
            "// Generated by tools/tutorial_site.py from the recording's render/timeline.json; edit neither by hand.\n"
            'window.tutorialTimeline = ' + json.dumps(data, ensure_ascii=False, allow_nan=False, indent=1) + ';\n')
        poster = Path(os.path.relpath(site / 'poster.jpg', args.readme.resolve().parent)).as_posix()
        place(args.readme, readme_block(timeline, media, url, poster))
    except (OSError, KeyError, IndexError, ValueError, subprocess.CalledProcessError) as error:
        detail = error.stderr.strip() if isinstance(error, subprocess.CalledProcessError) else error
        parser.exit(1, f'Tutorial site: {detail}\n')
    print(f'{site}: {len(timeline["lessons"])} lessons, {len(timeline["steps"])} steps, {movie.name} ({media["bytes"] / 1e6:.1f} MB)')
    print(f'{args.readme}: tutorial block links to {url}')


if __name__ == '__main__':
    sys.exit(main())
